#!/usr/bin/env python3
"""One-command pipeline: sample run -> scoring -> full run -> validation -> reports -> code.zip.

Usage (from repo root, with dataset/ present):  python3 code/run_all.py
Writes: sample_pred.csv, output.csv, code/evaluation/{evaluation_report,usage_report}.md, code.zip
"""
import argparse, csv, json, re, sys, zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE)); sys.path.insert(0, str(HERE / "evaluation"))
import main as app
from evaluate import evaluate, load
from audit.util import read_csv

S, E = "<!-- METRICS:START -->", "<!-- METRICS:END -->"


def rewrite_block(path, body):
    t = path.read_text(encoding="utf-8")
    block = f"{S}\n{body}\n{E}"
    path.write_text(re.sub(re.escape(S) + ".*?" + re.escape(E), lambda _: block, t, flags=re.S) if S in t else t + "\n" + block + "\n", encoding="utf-8")



def validate_output(out, req_file):
    ids = [r["case_id"] for r in read_csv(req_file)]
    rows = list(csv.DictReader(open(out, newline="", encoding="utf-8")))
    assert [r["case_id"] for r in rows] == sorted(ids), "row set/order mismatch"
    assert list(rows[0].keys()) == ["case_id", "deletion_status", "steps_json"]
    for r in rows:
        steps = json.loads(r["steps_json"])
        assert [s["step_no"] for s in steps] == list(range(1, len(steps) + 1))
    return len(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=str(HERE.parent))
    a = ap.parse_args()
    root = Path(a.root); ds = root / "dataset"
    rep = HERE / "evaluation" / "evaluation_report.md"
    if not (ds / "deletion_requests.csv").exists():
        sys.exit(f"dataset not found at {ds}")

    # 1) sample run + scoring
    if (ds / "sample_output.csv").exists():
        app.run(ds, "sample_deletion_requests.csv", root / "sample_pred.csv")
        gold, pred = load(ds / "sample_output.csv"), load(root / "sample_pred.csv")
        m = evaluate(pred, gold)
        lines = ["| Metric | Value |", "| --- | --- |"] + [f"| {k} | {v:.4f} |" if isinstance(v, float) else f"| {k} | {v} |" for k, v in m.items()]
        bad = [c for c in gold if pred.get(c, ("", []))[0] != gold[c][0] or pred.get(c) != gold[c]]
        lines += ["", f"Sample cases not matching gold exactly: {len(bad)} of {len(gold)}"]
        lines += [f"- `{c}`: gold {gold[c][0]} ({len(gold[c][1])} steps) vs pred {pred.get(c, ('missing',[]))[0]} ({len(pred.get(c, ('', []))[1])} steps)" for c in bad[:15]]
        rewrite_block(rep, "## Measured on sample set (auto-generated by run_all.py)\n" + "\n".join(lines))
    else:
        print("no sample_output.csv; skipping scoring")

    # 2) full run + validation
    out = root / "output.csv"
    app.run(ds, "deletion_requests.csv", out)
    n = validate_output(out, ds / "deletion_requests.csv")

    (HERE / "evaluation" / "usage_report.md").write_text(
        f"""# Token Usage and Cost Report

Final full-dataset run: {n} requests processed by `python3 code/run_all.py`.

The pipeline is fully deterministic and makes **no model calls**.

| Provider / model | Calls | Input tokens | Output tokens | Est. cost |
| --- | --- | --- | --- | --- |
| none | 0 | 0 | 0 | $0.00 |

Total tokens: 0. Average tokens per request: 0. Estimated cost: $0.00 total, $0.00 per request.
""", encoding="utf-8")

    # 4) package code.zip (no dataset, caches, or nested archives)
    import shutil
    shutil.copy(out, ds / "output.csv")
    zp = root / "code.zip"
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for p in [root / "README.md", *sorted((root / "code").rglob("*"))]:
            if p.is_file() and "__pycache__" not in p.parts and p.suffix not in (".zip", ".pyc"):
                z.write(p, p.relative_to(root))
                if "evaluation" in p.parts:
                    z.write(p, Path("evaluation") / p.name)
    print(f"validated {n} rows; wrote {out.name} and {zp.name}")


if __name__ == "__main__":
    main()
